/** Month and year, for dates far enough away that the day does not matter ("Oct 2027"). */
export function formatMonth(iso: string | null | undefined, lang: Lang): string {
  if (!iso) return "–";
  const m = /^(\d{4})-(\d{2})/.exec(iso);
  if (!m) return iso;
  const month = Number(m[2]) - 1;
  const name = lang === "fi" ? FI_MONTHS[month] : MONTHS[lang][month];
  return `${name ?? m[2]} ${m[1]}`;
}
